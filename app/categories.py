"""Автокатегоризация операций выписок и ручных расходов по ключевым словам.

Порядок правил важен: сначала строгие корпоративные ключи (налоги, зарплата,
аренда), затем личные категории (сообщения «расход: 500 кофе»), в конце —
общие («поставщик», «перевод»). Более специфичные — первыми."""

# Личные категории для коротких описаний из сообщений («расход: 500 кофе»)
PERSONAL_RULES: list[tuple[str, tuple[str, ...]]] = [
    ("Продукты", ("продукт", "супермаркет", "пятёроч", "пятероч", "магнит", "лента", "ашан", "перекрёст", "перекрест", "овощ", "хлеб")),
    ("Кафе и рестораны", ("кафе", "кофе", "ресторан", "столов", "фастфуд", "шаурм", "пицц", "доставка ед")),
    ("Транспорт", ("такси", "метро", "автобус", "троллейбус", "трамвай", "электричк", "бензин", "топлив", "заправк", "каршеринг", "проезд", "парковк")),
    ("Связь и интернет", ("связь", "интернет", "мобильн", "мтс", "билайн", "мегафон", "теле2", "ростелеком")),
    ("Здоровье", ("аптек", "лекарств", "врач", "клиник", "стоматолог", "анализ", "массаж")),
    ("Подписки", ("подписк", "нетфликс", "спотифай", "youtube", "ямусик", "плюс", "icloud")),
    ("Одежда и вещи", ("одежд", "обув", "сумк", "парфюм")),
    ("Развлечения", ("кино", "театр", "концерт", "билет", "настольн", "квест")),
    ("Дом и ремонт", ("стройматериал", "мебель", "бытова", "хозяйств", "канцеляр")),
    ("Подарки", ("подарок", "подарк", "цвет")),
]

# Корпоративные категории для выписок и регламентных документов
RULES: list[tuple[str, tuple[str, ...]]] = [
    ("Налоги и взносы", ("налог", "фнс", "пенсионн", "взнос", "таможен")),
    ("Зарплата", ("зарплат", "заработн", "ведомост", "фот", "оплата труда", "аванс")),
    ("Аренда", ("аренд", "лизинг")),
    ("Банк", ("комисси", "банковск", "обслуживание сч", "смс-информ")),
    ("Кредиты и проценты", ("кредит", "займ", "процент по")),
    ("Переводы", ("перевод", "перечисл", "транзит")),
    ("Касса", ("касс", "инкассац", "выручка налич")),
    ("Поставщики и подрядчики", ("поставщик", "подрядчик", "за товар", "за услуги", "счёт №", "счет №", "оплата по счёт")),
]


def categorize(description: str) -> str:
    d = (description or "").casefold()
    if not d:
        return "Прочее"
    for name, stems in PERSONAL_RULES + RULES:
        if any(stem in d for stem in stems):
            return name
    return "Прочее"
