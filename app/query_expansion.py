"""Расширение запросов для офлайн-поиска: аббревиатуры и финансовые синонимы.

Практика multi-query retrieval: один вопрос пользователя превращается в 2–3
варианта (исходный + обогащённые), каждый ищется отдельно, результаты сливаются
через RRF. Так «дебиторка» находит «дебиторскую задолженность», а «ндс» —
«налог на добавленную стоимость» даже без внешнего LLM API.
"""
from __future__ import annotations

import re

# Сокращения, которыми пишут пользователи -> полные названия из отчётности
ABBREVIATIONS = {
    "ндс": "налог на добавленную стоимость",
    "нма": "нематериальные активы",
    "ос": "основные средства",
    "дз": "дебиторская задолженность",
    "кз": "кредиторская задолженность",
    "она": "отложенные налоговые активы",
    "оно": "отложенные налоговые обязательства",
    "тмц": "товарно-материальные ценности",
    "фот": "фонд оплаты труда зарплата",
    "бфо": "бухгалтерская финансовая отчетность",
    "р-с": "расчётный счёт",
    "финрезультат": "финансовый результат прибыль",
}

# Группы синонимов: вхождение одного слова добавляет остальные
SYNONYM_GROUPS = [
    ("выручка", "продажи", "доходы от реализации"),
    ("расходы", "затраты", "издержки"),
    ("прибыль", "финрезультат", "доходы минус расходы"),
    ("дебиторка", "дебиторская задолженность"),
    ("кредиторка", "кредиторская задолженность"),
    ("запасы", "товарно-материальные ценности", "склад"),
    ("зарплата", "оплата труда", "фонд оплаты труда"),
    ("аренда", "арендные платежи", "лизинг"),
    ("налоги", "налоговые платежи", "налоговые обязательства"),
    ("деньги", "денежные средства", "касса"),
    ("долги", "задолженность", "дебиторская задолженность", "кредиторская задолженность"),
    ("баланс", "актив", "пассив"),
    ("автор", "руководитель", "подписавший", "фио", "представитель"),
    ("подписал", "руководитель", "подписавшего", "фио"),
    ("организация", "наименование", "юридическое лицо", "компания"),
    ("адрес", "местонахождение", "находится"),
    ("находится", "местонахождение", "адрес"),
    ("называется", "наименование", "название"),
    ("аудит", "аудитор", "аудиторская организация"),
    ("сотрудники", "численность", "персонал", "работники"),
]


def expand_query(query: str, max_variants: int = 2) -> list[str]:
    """-> [исходный запрос, обогащённый вариант]. Обогащение детерминировано,
    поэтому кэш эмбеддингов и повторяемость ответов не ломаются."""
    base = (query or "").strip()
    if not base:
        return [base]
    enriched = base

    for word, expansion in ABBREVIATIONS.items():
        if re.search(rf"(?<!\w){re.escape(word)}(?!\w)", base, re.IGNORECASE):
            enriched += f" {expansion}"

    for group in SYNONYM_GROUPS:
        for syn in group:
            head = syn.split()[0]
            if re.search(rf"(?<!\w){re.escape(head)}(?!\w)", base, re.IGNORECASE):
                additions = " ".join(g for g in group if g != syn)
                enriched += f" {additions}"
                break

    variants = [base]
    if enriched != base:
        variants.append(enriched)
    return variants[:max_variants]
