"""Генератор демонстрационного финансового отчёта для показа заказчику.

Создаёт «Финансовый_отчёт_ООО_Вектор_2023-2025.xlsx» — правдоподобный отчёт
растущей инжиниринговой компании, задействующий все возможности бота:

  лист 1 «Отчёт о финансовых результатах» — факты 2023–2025 + колонки
          «2025 (план)» и «2026 (план)» → вопросы, динамика, факт/план, прогноз;
  лист 2 «Расходы по элементам»    — итог + строки-дети (отступом) → drill-down
          «из чего состоит итого расходов»;
  лист 3 «Баланс»                  — активы и пассивы с детализацией;
  лист 4 «Выписка банка, руб.»     — операции IV квартала 2025 построчно →
          ledger-режим: помесячные факты + «операции за месяц» с категориями;
  лист 5 «Пояснительная записка»   — текст для RAG («кто руководитель?»);
  лист 6 «Риски и меры»            — короткий сфокусированный чанк —
          «что говорится о рисках?» находит его первым.

Все числа увязаны между собой (арифметика ОФР, элементы расходов = себестоимость
+ коммерческие + управленческие, баланс сходится) — бот отвечает на каверзные
вопросы заказчика без противоречий.

Запуск:    venv\\Scripts\\python.exe scripts\\make_demo_report.py
Проверка:  venv\\Scripts\\python.exe scripts\\verify_demo_report.py
"""
