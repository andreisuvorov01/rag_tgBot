# ------------------------------------------------------------------ сборка ---

def build() -> Path:
    wb = Workbook()

    # --- Лист 1: отчёт о финансовых результатах (факт + план) ---
    ws = wb.active
    ws.title = "Отчёт о финансовых результатах"
    ws["A1"] = "ООО «Вектор». Отчёт о финансовых результатах за 2023–2025 годы, тыс. руб."
    ws["A1"].font = TITLE
    # ярус шапки: вариант колонки (факт/план) — парсер берёт отсюда вариант значений
    for col, label in zip("BCDEF", ("Факт", "Факт", "Факт", "План", "План"), strict=True):
        ws[f"{col}2"] = label
        ws[f"{col}2"].font = BOLD
        ws[f"{col}2"].alignment = Alignment(horizontal="center")
    headers = ("Показатель", "2023", "2024", "2025", "2025 (план)", "2026 (план)")
    for c, h in enumerate(headers, start=1):
        ws.cell(row=3, column=c, value=h)
    _style_header(ws, 3, 6)
    for r, row in enumerate(OFR_ROWS, start=4):
        for c, v in enumerate(row, start=1):
            ws.cell(row=r, column=c, value=v)
    _fmt_numbers(ws, 4, 3 + len(OFR_ROWS), range(2, 7))
    for r in (4, 6, 9, 12, 13):  # выручка, валовая, прибыль от продаж, до налога, чистая
        for c in range(1, 7):
            ws.cell(row=r, column=c).font = BOLD
    ws.column_dimensions["A"].width = 34
    for col in "BCDEF":
        ws.column_dimensions[col].width = 13
    ws.freeze_panes = "B4"

    # --- Лист 2: расходы по экономическим элементам (итог + дети отступом) ---
    ws = wb.create_sheet("Расходы по элементам")
    ws["A1"] = "Расходы по обычным видам деятельности по экономическим элементам, тыс. руб."
    ws["A1"].font = TITLE
    for c, h in enumerate(("Показатель", "", "2023", "2024", "2025"), start=1):
        ws.cell(row=2, column=c, value=h or None)
    _style_header(ws, 2, 5)
    for r, row in enumerate(ELEMENT_ROWS, start=3):
        for c, v in enumerate(row, start=1):
            ws.cell(row=r, column=c, value=v)
    _fmt_numbers(ws, 3, 2 + len(ELEMENT_ROWS), range(3, 6))
    for c in range(1, 6):
        ws.cell(row=3, column=c).font = BOLD  # строка «Итого …»
    ws.column_dimensions["A"].width = 46
    ws.column_dimensions["B"].width = 32
    for col in "CDE":
        ws.column_dimensions[col].width = 13

    # --- Лист 3: бухгалтерский баланс ---
    ws = wb.create_sheet("Баланс")
    ws["A1"] = "Бухгалтерский баланс ООО «Вектор» на 31 декабря 2023–2025 гг., тыс. руб."
    ws["A1"].font = TITLE
    for c, h in enumerate(("Показатель", "", "2023", "2024", "2025"), start=1):
        ws.cell(row=2, column=c, value=h or None)
    _style_header(ws, 2, 5)
    for r, row in enumerate(BALANCE_ROWS, start=3):
        for c, v in enumerate(row, start=1):
            ws.cell(row=r, column=c, value=v)
    _fmt_numbers(ws, 3, 2 + len(BALANCE_ROWS), range(3, 6))
    for rr in (3, 8):  # «Итого активы» / «Итого пассивы»
        for c in range(1, 6):
            ws.cell(row=rr, column=c).font = BOLD
    ws.column_dimensions["A"].width = 22
    ws.column_dimensions["B"].width = 32
    for col in "CDE":
        ws.column_dimensions[col].width = 13

    # --- Лист 4: выписка банка (ledger-режим: построчные операции) ---
    # ВАЖНО: без титульной строки — парсер берёт заголовки колонок из строки 0
    # («Поступления»/«Списания» становятся именами показателей выписки).
    ws = wb.create_sheet("Выписка банка, руб.")
    for c, h in enumerate(("Дата", "Назначение платежа", "Поступления", "Списания"), start=1):
        ws.cell(row=1, column=c, value=h)
    _style_header(ws, 1, 4)
    for r, (d, desc, inc, exp) in enumerate(LEDGER_ROWS, start=2):
        ws.cell(row=r, column=1, value=d).number_format = DATE_FMT
        ws.cell(row=r, column=2, value=desc)
        if inc is not None:
            ws.cell(row=r, column=3, value=inc).number_format = NUM_FMT
        if exp is not None:
            ws.cell(row=r, column=4, value=exp).number_format = NUM_FMT
    ws.column_dimensions["A"].width = 12
    ws.column_dimensions["B"].width = 56
    ws.column_dimensions["C"].width = 15
    ws.column_dimensions["D"].width = 15
    ws.freeze_panes = "A2"

    # --- Лист 5: пояснительная записка (текст для RAG) ---
    ws = wb.create_sheet("Пояснительная записка")
    for r, para in enumerate(NOTE_MAIN, start=1):
        cell = ws.cell(row=r, column=1, value=para)
        cell.alignment = Alignment(wrap_text=True, vertical="top")
        if r == 1:
            cell.font = TITLE
    ws.column_dimensions["A"].width = 110

    # --- Лист 6: риски и меры (отдельный короткий чанк — выигрывает поиск) ---
    ws = wb.create_sheet("Риски и меры")
    for r, para in enumerate(NOTE_RISKS, start=1):
        cell = ws.cell(row=r, column=1, value=para)
        cell.alignment = Alignment(wrap_text=True, vertical="top")
        if r == 1:
            cell.font = TITLE
    ws.column_dimensions["A"].width = 110

    wb.save(OUT)
    return OUT


if __name__ == "__main__":
    path = build()
    print(f"Готово: {path}")
    print(f"Размер: {path.stat().st_size / 1024:.1f} КБ")
